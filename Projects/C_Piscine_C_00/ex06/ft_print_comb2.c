#include <unistd.h>
void	ft_print_comb2(void)
{
	char	d01;
	char	d02;
	char	d11;
	char	d12;

	d01 = '0';
	d02 = '0';
	d11 = '0';
	d12 = '1';
	while ((d01 - '0') * 10 + (d02 - '0') < 99)
	{
		while ((d11 - '0') * 10 + (d12 - '0') < 100)
		{
			write(1, &d01, 1);
			write(1, &d02, 1);
			write(1, &d11, 1);
			write(1, &d12, 1);
			if(!(d01 == '9' && d02 == '8' && d11 == '9' && d12 == '9'))
				write(2, ", ", 2);
			if(d12 != '9')
				d12++;
			else
			{
				d11++;
				d12 = '0';
			}
		}
		if(d02 != '9')
		{
			d02++;
			d12 = d02 + 1;
			d11 = d01;
		}
		else
		{
			d01++;
			d02 = '0';
		}

	}
}
int main(void)
{
	ft_print_comb2();
}
